import { LEGACY_FILTERS, type LegacyFilter } from "./legacyFilters";
import type { Category } from "./types";

// Deliberate creative grades, not calibrated or licensed stock emulations.
export interface Grade {
  exposure?: number;
  contrast?: number;
  saturation?: number;
  temperature?: number;
  tint?: number;
  black?: number;
  white?: number;
  gamma?: number;
  grain?: number;
  vignette?: number;
  shadow?: [number, number, number];
  light?: [number, number, number];
  curve?: [number, number, number, number, number];
  weights?: [number, number, number];
  bloom?: number;
  halation?: number;
  noise?: number;
  bits?: number;
  resolution?: number;
  sharpness?: number;
  flash?: number;
  leak?: number;
  dust?: number;
  aberration?: number;
  mapping?: "purple" | "turquoise" | "redscale" | "infrared";
  halftone?: boolean;
  date?: boolean;
}
export interface Filter {
  id: string;
  name: string;
  category: Category;
  description: string;
  grade?: Grade;
  legacy?: LegacyFilter;
}
function preset(
  category: Category,
  name: string,
  description: string,
  grade: Grade,
): Filter {
  return {
    id: name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/-$/, ""),
    name,
    category,
    description,
    grade,
  };
}
const film = (name: string, description: string, grade: Grade) =>
  preset("Film", name, description, grade);
const mono = (name: string, description: string, grade: Grade) =>
  preset("Black & White", name, description, { saturation: 0, ...grade });
const instant = (name: string, description: string, grade: Grade) =>
  preset("Instant", name, description, grade);
const digital = (name: string, description: string, grade: Grade) =>
  preset("Digital", name, description, { bits: 7, sharpness: 0.35, ...grade });
const disposable = (name: string, description: string, grade: Grade) =>
  preset("Disposable", name, description, grade);
const cinema = (name: string, description: string, grade: Grade) =>
  preset("Cinematic", name, description, grade);
const experimental = (name: string, description: string, grade: Grade) =>
  preset("Experimental", name, description, grade);

